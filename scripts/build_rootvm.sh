#!/usr/bin/env bash
# Buildroot integration script for Diosix Root VM and built-in guest images.
#
# Usage: build_rootvm.sh <config> <out_bin> <buildroot_dir> [arch] [rootvm_s]
#                        [extra_overlay_dir]
#
# Copyright (c) 2026 Chris Williams <chrisw@diosix.org>
# SPDX-License-Identifier: MIT

set -eo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=scripts/lib/buildroot_common.sh
. "${SCRIPT_DIR}/lib/buildroot_common.sh"

CONFIG_FILE="$1"
OUT_FILE="$2"
BUILDROOT_DIR="$3"
GUEST_ARCH="${4:-riscv64}"
ROOTVM_S_PATH="${5:-}"
EXTRA_OVERLAY_DIR="${6:-}"
BUILDROOT_URL="https://gitlab.com/buildroot.org/buildroot.git"
BUILDROOT_BRANCH="2026.02.x"
ALPINE_VER="3.24.3"
ALPINE_TAR="alpine-minirootfs-${ALPINE_VER}-riscv64.tar.gz"
ALPINE_SITE="https://dl-cdn.alpinelinux.org/alpine/v3.24/releases/riscv64"
ALPINE_URL="${ALPINE_SITE}/${ALPINE_TAR}"
ALPINE_SHA256="9714553757e7bf645eff5dcc52bdd206f358a7bed77874842567852e8326a51d"

if [ -z "$CONFIG_FILE" ] || [ -z "$OUT_FILE" ] || [ -z "$BUILDROOT_DIR" ]; then
    echo "Usage: $0 <config> <out_file> <buildroot_dir> [arch] [rootvm_s]" \
        "[extra_overlay_dir]"
    exit 1
fi

IS_ROOT_VM=0
IMAGE_LABEL="Guest VM ($(basename "$OUT_FILE"))"
case "$ROOTVM_S_PATH" in
    *.s)
        IS_ROOT_VM=1
        IMAGE_LABEL="Root VM"
        ;;
esac

mkdir -p "$(dirname "$OUT_FILE")"
mkdir -p "$(dirname "$BUILDROOT_DIR")"

HASH_FILE="${OUT_FILE}.sha256"
CURRENT_HASH=$(
    (
        find tools/overlay-common -type f \
            -exec sha256sum {} + 2>/dev/null
        if [ -n "$EXTRA_OVERLAY_DIR" ] && [ -d "$EXTRA_OVERLAY_DIR" ]; then
            find "$EXTRA_OVERLAY_DIR" -type f \
                -exec sha256sum {} + 2>/dev/null
        fi
        find tools/diosix-ctl/src hypervisor/interface -name '*.zig' \
            | sort | xargs cat | sha256sum
        if [ "$IS_ROOT_VM" -eq 1 ]; then
            find tools/diosix-gui/src tools/guest-shim -name '*.zig' \
                | sort | xargs cat | sha256sum
            sha256sum tools/guest-shim/linker.ld \
                tools/diosix-gui/assets/* tools/alsa-init/* 2>/dev/null
        fi
        sha256sum "$CONFIG_FILE" "$0" "${SCRIPT_DIR}/lib/buildroot_common.sh" \
            "${SCRIPT_DIR}/assemble_alpine_rootfs.sh" \
            "$(dirname "$CONFIG_FILE")"/*.fragment tools/driver/* 2>/dev/null
    ) | awk '{print $1}' | sort | sha256sum | cut -d' ' -f1
)

write_rootvm_s() {
    if [ -n "$ROOTVM_S_PATH" ]; then
        mkdir -p "$(dirname "$ROOTVM_S_PATH")"
        if [ "$IS_ROOT_VM" -eq 1 ]; then
            local abs_out
            abs_out=$(realpath "$OUT_FILE")
            cat <<EOF > "$ROOTVM_S_PATH"
# Dynamically generated by build_rootvm.sh. DO NOT EDIT.
# Modification hash: $CURRENT_HASH
.section .rootvm, "a"
.global root_vm_start
.global root_vm_end
.balign 4096
root_vm_start:
.incbin "$abs_out"
root_vm_end:
EOF
        else
            printf "%s\n" "$CURRENT_HASH" > "$ROOTVM_S_PATH"
        fi
    fi
}

# 1. Cache Check.
if [ -f "$OUT_FILE" ] && [ -f "$HASH_FILE" ]; then
    RECORDED_HASH=$(cat "$HASH_FILE")
    if [ "$CURRENT_HASH" = "$RECORDED_HASH" ]; then
        SIZE=$(du -h "$OUT_FILE" | cut -f1)
        H_SHORT="${CURRENT_HASH:0:12}"
        MSG="${IMAGE_LABEL} up-to-date (${BOLD}${GUEST_ARCH}${RESET}"
        log_ok "${MSG} | ${SIZE} | ${H_SHORT}...). Skipped."
        write_rootvm_s
        exit 0
    fi
fi

log_banner "$IMAGE_LABEL"
log_info "Target architecture : ${BOLD}${GUEST_ARCH}${RESET}"
log_info "Config profile      : $(basename "$CONFIG_FILE")"
log_info "Parallel jobs       : $(nproc) host CPU cores"
log_info "Destination ELF     : $OUT_FILE"

# 2. Build Guest Management Utilities.
log_step "[1/5] Cross-compiling guest management tools..."
mkdir -p "$BUILDROOT_DIR"
DYNAMIC_OVERLAY="$(realpath "$BUILDROOT_DIR")/overlay-dynamic"
rm -rf "$DYNAMIC_OVERLAY"
mkdir -p "$DYNAMIC_OVERLAY/usr/sbin" "$DYNAMIC_OVERLAY/usr/bin"

ZIG_TARGET="${GUEST_ARCH}-linux-musl"
log_info "Compiling diosix-ctl for ${BOLD}${ZIG_TARGET}${RESET}..."
zig build-exe -target "$ZIG_TARGET" -O ReleaseSmall -fstrip \
    --dep interface -Mroot=tools/diosix-ctl/src/main.zig \
    -Minterface=hypervisor/interface/lib.zig \
    --name diosix-ctl \
    -femit-bin="$DYNAMIC_OVERLAY/usr/sbin/diosix-ctl" >/dev/null 2>&1
ln -sf diosix-ctl "$DYNAMIC_OVERLAY/usr/sbin/dsx"
ln -sf ../sbin/diosix-ctl "$DYNAMIC_OVERLAY/usr/bin/dsx"
log_ok "Installed diosix-ctl and 'dsx' symlink in overlay."

if [ -d "tools/guest-shim" ]; then
    log_info "Compiling freestanding S-mode guest bootloader shim..."
    SHIM_DIR="$DYNAMIC_OVERLAY/usr/share/diosix/shim"
    SHIM_ELF="guest-shim-riscv64.elf"
    mkdir -p "$SHIM_DIR"
    if zig build-exe -target riscv64-freestanding-none \
        -O ReleaseSmall -fstrip -mcmodel=medium \
        --script tools/guest-shim/linker.ld \
        --dep interface -Mroot=tools/guest-shim/src/main.zig \
        -Minterface=hypervisor/interface/lib.zig --name "$SHIM_ELF" \
        -femit-bin="${SHIM_DIR}/${SHIM_ELF}" >/dev/null 2>&1; then
        ln -sf "shim/${SHIM_ELF}" \
            "$DYNAMIC_OVERLAY/usr/share/diosix/guest-shim.bin"
        log_ok "Installed ${SHIM_ELF} in overlay (/usr/share/diosix/shim/)."
    else
        log_warn "Failed to cross-compile ${SHIM_ELF}."
    fi
fi

if [ -d "tools/diosix-gui" ]; then
    log_info "Compiling diosix-gui for ${BOLD}${ZIG_TARGET}${RESET}..."
    if zig build-exe -target "$ZIG_TARGET" -O ReleaseFast -fstrip \
        --dep interface --dep questrial_ttf \
        --dep dm_mono_ttf --dep intro_wav \
        -Mroot=tools/diosix-gui/src/main.zig \
        -Minterface=hypervisor/interface/lib.zig \
        -Mquestrial_ttf=tools/diosix-gui/assets/Questrial-Regular.ttf \
        -Mdm_mono_ttf=tools/diosix-gui/assets/DMMono-Regular.ttf \
        -Mintro_wav=tools/diosix-gui/assets/intro.wav \
        --name diosix-gui \
        -femit-bin="$DYNAMIC_OVERLAY/usr/bin/diosix-gui"; then
        ln -sf diosix-gui "$DYNAMIC_OVERLAY/usr/bin/diosix-wm"
        mkdir -p "$DYNAMIC_OVERLAY/usr/share/licenses/diosix"
        cp -f LICENSE.md \
            "$DYNAMIC_OVERLAY/usr/share/licenses/diosix/LICENSE.md"
        log_ok "Installed diosix-gui and 'diosix-wm' symlink in overlay."
    else
        log_err "Failed to cross-compile diosix-gui for ${ZIG_TARGET}."
        exit 1
    fi
fi

if [ -f "tools/alsa-init/main.c" ]; then
    log_info "Compiling diosix-alsa-init for ${ZIG_TARGET}..."
    ALSA_BIN="$DYNAMIC_OVERLAY/usr/sbin/diosix-alsa-init"
    if zig cc -target "$ZIG_TARGET" -Os -s \
        tools/alsa-init/main.c -o "$ALSA_BIN" 2>/dev/null; then
        chmod +x "$ALSA_BIN"
        log_ok "Installed diosix-alsa-init in overlay (/usr/sbin/)."
    fi
fi

# Clean lingering private keys from previous target builds and set permissions.
if [ -d "$BUILDROOT_DIR/output/target/etc/diosix/keys" ]; then
    rm -f "$BUILDROOT_DIR"/output/target/etc/diosix/keys/id_*
fi
chmod 0755 tools/overlay-common/etc/diosix 2>/dev/null || true
chmod 0644 tools/overlay-common/etc/diosix/*.toml \
    tools/overlay-common/etc/diosix/*.md 2>/dev/null || true
chmod 0755 tools/overlay-common/etc/init.d/S* 2>/dev/null || true
if [ -d "tools/overlay-common/etc/diosix/keys" ]; then
    chmod 0700 tools/overlay-common/etc/diosix/keys 2>/dev/null || true
fi
if [ -n "$EXTRA_OVERLAY_DIR" ] && [ -d "$EXTRA_OVERLAY_DIR" ]; then
    chmod 0755 "$EXTRA_OVERLAY_DIR"/etc/init.d/S* 2>/dev/null || true
fi

# 3. Buildroot Workspace Setup.
log_step "[2/5] Preparing Buildroot workspace..."
if [ ! -d "$BUILDROOT_DIR/.git" ]; then
    TEMP_CLONE=$(mktemp -d -p "$(dirname "$BUILDROOT_DIR")")
    PRIMARY_BR="$(dirname "$BUILDROOT_DIR")/buildroot-${GUEST_ARCH}"
    if [ -d "$PRIMARY_BR/.git" ] && \
       [ "$(realpath -m "$BUILDROOT_DIR")" != \
         "$(realpath -m "$PRIMARY_BR")" ]; then
        log_info "Cloning Buildroot locally from ${PRIMARY_BR}..."
        git clone --local "$(realpath "$PRIMARY_BR")" "$TEMP_CLONE" \
            >/dev/null 2>&1
    else
        log_info "Cloning Buildroot (${BUILDROOT_BRANCH}) -> ${BUILDROOT_DIR}"
        git clone --depth 1 -b "$BUILDROOT_BRANCH" \
            "$BUILDROOT_URL" "$TEMP_CLONE"
    fi
    mv "$BUILDROOT_DIR/dl" "$TEMP_CLONE/dl" 2>/dev/null || true
    mv "$BUILDROOT_DIR/overlay-dynamic" \
        "$TEMP_CLONE/overlay-dynamic" 2>/dev/null || true
    rm -rf "$BUILDROOT_DIR"
    mv "$TEMP_CLONE" "$BUILDROOT_DIR"
    log_ok "Buildroot workspace ready."
else
    log_ok "Buildroot workspace found."
fi

# 4. Configure Buildroot.
log_step "[3/5] Applying Buildroot and Linux kernel defconfig..."
ABS_CONFIG=$(realpath "$CONFIG_FILE")

if [ -f "$BUILDROOT_DIR/.config" ]; then
    cp "$BUILDROOT_DIR/.config" "$BUILDROOT_DIR/.config.old"
fi

make -C "$BUILDROOT_DIR" BR2_DEFCONFIG="$ABS_CONFIG" defconfig >/dev/null

OVERLAY_LIST=$(realpath tools/overlay-common)
if [ -n "$EXTRA_OVERLAY_DIR" ] && [ -d "$EXTRA_OVERLAY_DIR" ]; then
    OVERLAY_LIST="${OVERLAY_LIST} $(realpath "$EXTRA_OVERLAY_DIR")"
fi
OVERLAY_LIST="${OVERLAY_LIST} ${DYNAMIC_OVERLAY}"

SHARED_DL_DIR="$(realpath "$(dirname "$BUILDROOT_DIR")")/dl"
mkdir -p "$SHARED_DL_DIR"
echo "BR2_DL_DIR=\"$SHARED_DL_DIR\"" >> "$BUILDROOT_DIR/.config"

USE_ALPINE_NODE=0
if [ "$(basename "$CONFIG_FILE")" = "riscv64-linux-node.config" ] && \
   [ "$GUEST_ARCH" = "riscv64" ]; then
    USE_ALPINE_NODE=1
fi

if [ "$USE_ALPINE_NODE" -eq 1 ]; then
    ALPINE_PATH="${SHARED_DL_DIR}/${ALPINE_TAR}"
    if [ ! -f "$ALPINE_PATH" ]; then
        log_info "Downloading ${ALPINE_TAR}..."
        if command -v curl >/dev/null 2>&1; then
            curl -fsSL "$ALPINE_URL" -o "${ALPINE_PATH}.part"
        else
            wget -q -O "${ALPINE_PATH}.part" "$ALPINE_URL"
        fi
        mv -f "${ALPINE_PATH}.part" "$ALPINE_PATH"
    fi
    if ! printf "%s  %s\n" "$ALPINE_SHA256" "$ALPINE_PATH" | \
         sha256sum -c - >/dev/null 2>&1; then
        rm -f "$ALPINE_PATH"
        log_err "SHA-256 verification failed for ${ALPINE_TAR}."
        exit 1
    fi
    log_ok "Verified ${ALPINE_TAR} (SHA-256: ${ALPINE_SHA256:0:16}...)."
    ASSEMBLE_SH="$(realpath "${SCRIPT_DIR}/assemble_alpine_rootfs.sh")"
    COMMON_OV="$(realpath tools/overlay-common)"
    ARGS_STR="${ALPINE_PATH} ${COMMON_OV} ${DYNAMIC_OVERLAY}"
    echo "BR2_ROOTFS_OVERLAY=\"\"" >> "$BUILDROOT_DIR/.config"
    echo "BR2_ROOTFS_POST_FAKEROOT_SCRIPT=\"${ASSEMBLE_SH}\"" \
        >> "$BUILDROOT_DIR/.config"
    echo "BR2_ROOTFS_POST_SCRIPT_ARGS=\"${ARGS_STR}\"" \
        >> "$BUILDROOT_DIR/.config"
else
    echo "BR2_ROOTFS_OVERLAY=\"$OVERLAY_LIST\"" >> "$BUILDROOT_DIR/.config"
fi

GETTY_PORT="hvc0"
if [ "$GUEST_ARCH" = "aarch64" ]; then
    GETTY_PORT="ttyAMA0"
elif [ "$GUEST_ARCH" = "x86_64" ]; then
    GETTY_PORT="ttyS0"
fi
echo "BR2_TARGET_GENERIC_GETTY_PORT=\"$GETTY_PORT\"" >> "$BUILDROOT_DIR/.config"
echo "BR2_JLEVEL=0" >> "$BUILDROOT_DIR/.config"

if [ -f "$BUILDROOT_DIR/.config.old" ]; then
    OLD_MUSL=$(grep -E 'BR2_TOOLCHAIN_USES_MUSL=y|MUSL_STABLE=y' \
        "$BUILDROOT_DIR/.config.old" || true)
    NEW_MUSL=$(grep -E 'BR2_TOOLCHAIN_USES_MUSL=y|MUSL_STABLE=y' \
        "$BUILDROOT_DIR/.config" || true)
    if { [ -z "$OLD_MUSL" ] && [ -n "$NEW_MUSL" ]; } || \
       { [ -n "$OLD_MUSL" ] && [ -z "$NEW_MUSL" ]; }; then
        log_info "Toolchain libc changed. Cleaning Buildroot output..."
        rm -rf "$BUILDROOT_DIR/output"
    fi
fi

make -C "$BUILDROOT_DIR" olddefconfig >/dev/null

if [ -f "$BUILDROOT_DIR/.config.old" ]; then
    OLD_KV=$(grep -E '^BR2_LINUX_KERNEL_VERSION=' \
        "$BUILDROOT_DIR/.config.old" | cut -d'"' -f2 || true)
    NEW_KV=$(grep -E '^BR2_LINUX_KERNEL_VERSION=' \
        "$BUILDROOT_DIR/.config" | cut -d'"' -f2 || true)
    if [ "$OLD_KV" != "$NEW_KV" ] && [ -n "$OLD_KV" ]; then
        log_info "Kernel version changed ($OLD_KV -> $NEW_KV). Cleaning..."
        make -C "$BUILDROOT_DIR" \
            linux-dirclean linux-headers-dirclean >/dev/null 2>&1 || true
    fi
    OLD_WESTON=$(grep -E '^(# )?BR2_PACKAGE_WESTON' \
        "$BUILDROOT_DIR/.config.old" || true)
    NEW_WESTON=$(grep -E '^(# )?BR2_PACKAGE_WESTON' \
        "$BUILDROOT_DIR/.config" || true)
    if [ "$OLD_WESTON" != "$NEW_WESTON" ] && [ -n "$OLD_WESTON" ]; then
        log_info "Weston options changed. Reconfiguring weston..."
        make -C "$BUILDROOT_DIR" weston-dirclean >/dev/null 2>&1 || true
    fi
    rm -f "$BUILDROOT_DIR/.config.old"
fi
log_ok "Configured guest environment (getty: ${GETTY_PORT}, jobs: $(nproc))."

# 5. Fetch and patch Kernel.
log_step "[4/5] Preparing Linux kernel with /dev/diosix character driver..."
WGET_EXTRA_ARGS=""
if wget --version 2>&1 | head -1 | grep -q "Wget2"; then
    WGET_EXTRA_ARGS='BR2_WGET="wget -nd -t 3"'
fi
inject_diosix_driver "$BUILDROOT_DIR" "$WGET_EXTRA_ARGS"

# 6. Build Image with Real-Time Progress Monitor.
log_step "[5/5] Compiling Linux kernel and ${IMAGE_LABEL} ($(nproc) jobs)..."
START_TIME=$(date +%s)
run_buildroot_monitored "$BUILDROOT_DIR" "$WGET_EXTRA_ARGS" "$START_TIME"

mkdir -p "$(dirname "$OUT_FILE")"
IMAGE_PATH="$BUILDROOT_DIR/output/images/vmlinux"
if [ ! -f "$IMAGE_PATH" ]; then
    echo -e "\n${BOLD}${RED}Error:${RESET} Missing image '$IMAGE_PATH'!"
    exit 1
fi

cp "$IMAGE_PATH" "$OUT_FILE"
echo "$CURRENT_HASH" > "$HASH_FILE"
write_rootvm_s

END_TIME=$(date +%s)
ELAPSED=$((END_TIME - START_TIME))
SIZE=$(du -h "$OUT_FILE" | cut -f1)

DONE_MSG="${BOLD}${GREEN}✓ ${IMAGE_LABEL} build complete!${RESET}"
echo -e "\n${DONE_MSG} (${BOLD}${SIZE}${RESET} in ${ELAPSED}s)"
log_info "Kernel image : ${BOLD}$OUT_FILE${RESET}"
log_info "Hash check   : ${CURRENT_HASH:0:16}..."
if [ -n "$ROOTVM_S_PATH" ]; then
    log_info "Descriptor   : $ROOTVM_S_PATH"
fi
echo ""
