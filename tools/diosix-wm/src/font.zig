pub fn getGlyphs() *const [95]Glyph {
    return switch (current_font) {
        .henry => &HENRY_GLYPHS,
        .daydream => &DAYDREAM_GLYPHS,
    };
}

pub fn getGlyph(c: u8) ?Glyph {
    if (c >= 32 and c <= 126) {
        return getGlyphs()[c - 32];
    }
    return null;
}

pub fn measureText(text: []const u8, scale: u32) TextMetrics {
    const glyphs = getGlyphs();
    var w: u32 = 0;
    for (text) |c| {
        if (c >= 32 and c <= 126) {
            w += glyphs[c - 32].advance;
        } else if (c == ' ') {
            w += 5;
        } else if (c == '\t') {
            w += 20;
        } else {
            w += 6;
        }
    }
    return .{
        .width = w * scale,
        .height = GLYPH_HEIGHT * scale,
    };
}

pub fn drawChar(surface: *fb.Surface, c: u8, x: i32, y: i32, color: u32) void {
    if (c < 32 or c > 126) return;
    const glyph = getGlyphs()[c - 32];
    drawGlyph(surface, glyph, x, y, color);
}

pub fn drawGlyph(surface: *fb.Surface, glyph: Glyph, x: i32, y: i32, color: u32) void {
    for (glyph.rows, 0..) |row_val, r| {
        if (row_val == 0) continue;
        const py = y + @as(i32, @intCast(r));
        var bit: u5 = 0;
        while (bit < 16) : (bit += 1) {
            const shift: u4 = @intCast(15 - bit);
            if ((row_val & (@as(u16, 1) << shift)) != 0) {
                surface.setPixel(x + @as(i32, @intCast(bit)), py, color);
            }
        }
    }
}

pub fn drawText(surface: *fb.Surface, text: []const u8, x: i32, y: i32, color: u32) void {
    const glyphs = getGlyphs();
    var cur_x = x;
    for (text) |c| {
        if (c >= 32 and c <= 126) {
            const glyph = glyphs[c - 32];
            drawGlyph(surface, glyph, cur_x, y, color);
            cur_x += @intCast(glyph.advance);
        } else if (c == ' ') {
            cur_x += 5;
        } else if (c == '\t') {
            cur_x += 20;
        }
    }
}

pub fn drawTextScaled(surface: *fb.Surface, text: []const u8, x: i32, y: i32, scale: u32, color: u32) void {
    if (scale <= 1) {
        drawText(surface, text, x, y, color);
        return;
    }
    const glyphs = getGlyphs();
    var cur_x = x;
    for (text) |c| {
        if (c >= 32 and c <= 126) {
            const glyph = glyphs[c - 32];
            for (glyph.rows, 0..) |row_val, r| {
                if (row_val == 0) continue;
                const py = y + @as(i32, @intCast(r * scale));
                var bit: u5 = 0;
                while (bit < 16) : (bit += 1) {
                    const shift: u4 = @intCast(15 - bit);
                    if ((row_val & (@as(u16, 1) << shift)) != 0) {
                        const px = cur_x + @as(i32, @intCast(@as(u32, bit) * scale));
                        surface.fillRect(.{ .x = px, .y = py, .width = scale, .height = scale }, color);
                    }
                }
            }
            cur_x += @as(i32, @intCast(@as(u32, glyph.advance) * scale));
        } else if (c == ' ') {
            cur_x += @as(i32, @intCast(5 * scale));
        }
    }
}
